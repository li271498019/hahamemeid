"""Generate the data libraries used by the Haha Dog contracts.

  src/hahadog/HahaDogWeights.sol  int8 weights, int16 biases, prototypes, cell tables
  src/hahadog/HahaDogTables.sol   palette, background masks, trait templates, names

Usage: python gen_solidity.py   (run from anywhere; rewrites both files)
"""
import os

import hahadog_ref as R
from backgrounds import STYLES

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
W = R.WEIGHTS

OFF = {}


def i8(v):
    assert -128 <= v <= 127
    return (v & 0xFF).to_bytes(1, "big")


def i16(v):
    assert -32768 <= v <= 32767
    return (v & 0xFFFF).to_bytes(2, "big")


def weights_blob():
    out = bytearray()
    OFF["W1"] = len(out)
    for row in W["layers"][0]["W"]:
        out += b"".join(i8(x) for x in row)
    OFF["W2"] = len(out)
    for row in W["layers"][1]["W"]:
        out += b"".join(i8(x) for x in row)
    OFF["W3"] = len(out)
    for row in W["W_out"]:
        out += b"".join(i8(x) for x in row)
    OFF["B1"] = len(out)
    out += b"".join(i16(x) for x in W["layers"][0]["b"])
    OFF["B2"] = len(out)
    out += b"".join(i16(x) for x in W["layers"][1]["b"])
    OFF["B3"] = len(out)
    out += b"".join(i16(x) for x in W["b_out"])
    OFF["P"] = len(out)
    for a, b in W["P"]:
        out += i8(a) + i8(b)
    OFF["C"] = len(out)
    for c in W["C"]:
        assert 0 <= c < 1 << 24
        out += c.to_bytes(3, "big")
    OFF["VC"] = len(out)
    out += bytes(W["var_cells"])
    OFF["VM"] = len(out)
    out += b"".join(m.to_bytes(2, "big") for m in W["var_masks"])
    OFF["END"] = len(out)
    return bytes(out)


def const_outline():
    m = 0
    for k, v in W["const_cells"].items():
        assert v in (0, 1)
        if v == 1:
            m |= 1 << int(k)
    return m


def write_weights():
    blob = weights_blob()
    assert [len(l["W"]) for l in W["layers"]] == [64, 32] and len(W["W_out"]) == 224
    assert W["groups"] == [7, 8, 6, 5] and len(W["var_cells"]) == 99 and W["SH"] == 24
    lines = [
        "// SPDX-License-Identifier: MIT",
        "pragma solidity 0.8.28;",
        "",
        "/// @notice Generated by haha-dog/reference/gen_solidity.py from haha-dog/model/weights-int8.json. Do not edit.",
        "library HahaDogWeights {",
        "    uint256 internal constant M1 = %d;" % W["layers"][0]["M"],
        "    uint256 internal constant M2 = %d;" % W["layers"][1]["M"],
        "    uint256 internal constant SHIFT = %d;" % W["SH"],
        "    uint256 internal constant CONST_OUTLINE = 0x%032x;" % const_outline(),
    ]
    for k in ["W1", "W2", "W3", "B1", "B2", "B3", "P", "C", "VC", "VM", "END"]:
        lines.append("    uint256 internal constant OFF_%s = %d;" % (k, OFF[k]))
    lines.append('    bytes internal constant DATA = hex"%s";' % blob.hex())
    lines.append("}")
    open(os.path.join(ROOT, "src", "hahadog", "HahaDogWeights.sol"), "w").write("\n".join(lines) + "\n")
    open(os.path.join(ROOT, "haha-dog", "reference", "model-data.bin"), "wb").write(blob)
    return blob


def mask_of(style_idx, tone_pred):
    fn = STYLES[style_idx][1]
    base = (10, 20, 30)
    t = R.tones(base)
    im = fn(t, None, 6)
    m = 0
    for y in range(24):
        for x in range(24):
            if tone_pred(tuple(int(v) for v in im[y, x]), t):
                m |= 1 << (y * 24 + x)
    return m


def words(m):
    return [(m >> (256 * i)) & ((1 << 256) - 1) for i in range(3)]


def check_backgrounds():
    """Masks + rules below must reproduce model/backgrounds.py for every base color."""
    for color in range(8):
        for style in range(5):
            ref = R.background_image(style, color)
            got = rule_image(style, color)
            assert ref == got, (style, color)


def tone(c, k):
    if k == "base":
        return c
    if k == "dark":
        return tuple(v * 3 // 4 for v in c)
    if k == "light":
        return tuple((v * 3 + 255) // 4 for v in c)
    if k == "night":
        return tuple(v * 5 // 8 for v in c)


GLITCH_BARS = [(2, 0, 9, 0), (3, 14, 24, 1), (7, 3, 6, 1), (8, 18, 24, 0), (12, 0, 4, 0), (13, 20, 24, 1)]
BAR_RGB = [(255, 242, 117), (255, 63, 164)]


def rule_image(style, color):
    c = R.BG[color]
    im = [[None] * 24 for _ in range(24)]
    for y in range(24):
        for x in range(24):
            p = y * 24 + x
            if style in (0, 4):
                v = tone(c, "dark") if y & 1 else c
            elif style == 1:
                v = tone(c, "light") if (SUN >> p) & 1 else c
            elif style == 2:
                v = R.STAR if (STARS >> p) & 1 else tone(c, "night")
            else:
                v = R.STAR if (MOON >> p) & 1 else tone(c, "night")
            im[y][x] = v
    if style == 4:
        for (y, x0, x1, k) in GLITCH_BARS:
            for x in range(x0, x1):
                im[y][x] = BAR_RGB[k]
    return im


SUN = mask_of(1, lambda px, t: px == t["light"])
STARS = mask_of(2, lambda px, t: px == R.STAR)
MOON = mask_of(3, lambda px, t: px == R.STAR)


def hexrgb(lst):
    return "".join("%02x%02x%02x" % c for c in lst)


def names(lst):
    return "|".join(lst)


def write_tables():
    check_backgrounds()
    L = [
        "// SPDX-License-Identifier: MIT",
        "pragma solidity 0.8.28;",
        "",
        "/// @notice Generated by haha-dog/reference/gen_solidity.py. Do not edit.",
        "library HahaDogTables {",
    ]
    for nm, m in [("SUN", SUN), ("STARS", STARS), ("MOON", MOON)]:
        for i, w in enumerate(words(m)):
            L.append("    uint256 internal constant %s%d = 0x%064x;" % (nm, i, w))
    L.append('    bytes internal constant FUR = hex"%s";' % hexrgb(R.FUR))
    L.append('    bytes internal constant MARK = hex"%s";' % hexrgb(R.MARK))
    L.append('    bytes internal constant CLOTH = hex"%s";' % hexrgb(R.CLOTH))
    L.append('    bytes internal constant ACC = hex"%s";' % hexrgb(R.ACC))
    L.append('    bytes internal constant GLOW = hex"%s";' % hexrgb(R.GLOW))
    L.append('    bytes internal constant BG = hex"%s";' % hexrgb(R.BG))
    L.append('    bytes internal constant GLITCH = hex"%s";' % "".join("%02x%02x%02x%02x" % b for b in GLITCH_BARS))
    L.append('    bytes internal constant PLACEHOLDER = hex"%s";' % bytes(R.placeholder_cells()).hex())
    for cat in R.CATEGORIES:
        t = R.TEMPLATES[cat]
        L.append('    bytes internal constant %s_CELLS = hex"%s";' % (cat.upper(), bytes(t["cells"]).hex()))
        L.append('    bytes internal constant %s_TABLE = hex"%s";'
                 % (cat.upper(), bytes(v for row in t["table"] for v in row).hex()))
    for k in ["head", "eyes", "mouth", "neck", "fur", "style"]:
        L.append('    bytes internal constant PTS_%s = hex"%s";' % (k.upper(), bytes(R.POINTS[k]).hex()))
    L.append("    uint256 internal constant TIER_RARE = %d;" % R.TIER_MIN[1])
    L.append("    uint256 internal constant TIER_EPIC = %d;" % R.TIER_MIN[2])
    L.append("    uint256 internal constant TIER_LEGENDARY = %d;" % R.TIER_MIN[3])
    for nm, lst in [("FUR", R.FUR_NAMES), ("CLOTH", R.CLOTH_NAMES), ("ACC", R.ACC_NAMES),
                    ("GLOW", R.GLOW_NAMES), ("BG", R.BG_NAMES), ("STYLE", R.STYLE_NAMES),
                    ("HEAD", R.HEAD_NAMES), ("EYES", R.EYES_NAMES), ("MOUTH", R.MOUTH_NAMES),
                    ("NECK", R.NECK_NAMES), ("TIER", R.TIER_NAMES)]:
        L.append('    bytes internal constant N_%s = "%s";' % (nm, names(lst)))
    L.append('    string internal constant DESCRIPTION = "%s";' % R.DESCRIPTION)
    L.append("}")
    open(os.path.join(ROOT, "src", "hahadog", "HahaDogTables.sol"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    os.makedirs(os.path.join(ROOT, "src", "hahadog"), exist_ok=True)
    blob = write_weights()
    write_tables()
    print("weights blob", len(blob), "bytes; offsets", OFF)
    print("keccak256(model-data.bin) = 0x" + R.keccak256(blob).hex())
