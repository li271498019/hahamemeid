  function current() {
    var lang = document.documentElement.dataset.lang;
    return lang === "en" ? "en" : "zh";
  }

  function t(key) {
    var lang = current();
    var table = STR[lang] || STR.zh;
    if (Object.prototype.hasOwnProperty.call(table, key)) return table[key];
    if (Object.prototype.hasOwnProperty.call(STR.zh, key)) return STR.zh[key];
    return "";
  }

  function fill(key, vars) {
    return t(key).replace(/\{(\w+)\}/g, function (_, name) {
      return vars && vars[name] != null ? String(vars[name]) : "";
    });
  }

  function pad(n) { return n < 10 ? "0" + n : String(n); }

  function asDate(value) {
    if (value == null || value === "") return null;
    if (value instanceof Date) return isNaN(value.getTime()) ? null : value;
    if (typeof value === "number") return new Date(value < 1e12 ? value * 1000 : value);
    var s = String(value).trim();
    if (/^\d+$/.test(s)) {
      var n = Number(s);
      return new Date(n < 1e12 ? n * 1000 : n);
    }
    var d = new Date(s);
    return isNaN(d.getTime()) ? null : d;
  }

  /* 英文一律 UTC，中文一律 UTC+8，并且标出时区。 */
  function formatTime(value) {
    var d = asDate(value);
    if (!d) return "";
    if (current() === "zh") {
      var shifted = new Date(d.getTime() + 8 * 3600 * 1000);
      return shifted.getUTCFullYear() + "年"
        + pad(shifted.getUTCMonth() + 1) + "月"
        + pad(shifted.getUTCDate()) + "日 "
        + pad(shifted.getUTCHours()) + ":"
        + pad(shifted.getUTCMinutes()) + ":"
        + pad(shifted.getUTCSeconds())
        + " UTC+8";
    }
    return d.getUTCFullYear() + "-"
      + pad(d.getUTCMonth() + 1) + "-"
      + pad(d.getUTCDate()) + " "
      + pad(d.getUTCHours()) + ":"
      + pad(d.getUTCMinutes()) + ":"
      + pad(d.getUTCSeconds())
      + " UTC";
  }

  function cooldown(unixSec) {
    var d = asDate(unixSec);
    if (!d) return "";
    if (current() === "zh") {
      var shifted = new Date(d.getTime() + 8 * 3600 * 1000);
      var body = shifted.getUTCFullYear() + "年"
        + pad(shifted.getUTCMonth() + 1) + "月"
        + pad(shifted.getUTCDate()) + "日 "
        + pad(shifted.getUTCHours()) + ":"
        + pad(shifted.getUTCMinutes()) + ":"
        + pad(shifted.getUTCSeconds());
      return "冷却期：" + body + "（UTC+8）";
    }
    var bodyEn = d.getUTCFullYear() + "-"
      + pad(d.getUTCMonth() + 1) + "-"
      + pad(d.getUTCDate()) + " "
      + pad(d.getUTCHours()) + ":"
      + pad(d.getUTCMinutes()) + ":"
      + pad(d.getUTCSeconds());
    return "Cooldown until: " + bodyEn + " UTC";
  }

